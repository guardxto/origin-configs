#!/bin/bash
# Rebuild nginx's trusted-proxy list from the ranges your provider publishes,
# test the configuration, then reload. Run it daily from cron or a systemd timer:
#   17 4 * * * root SOURCES="https://example.net/ips-v4 https://example.net/ips-v6" /usr/local/sbin/update-ranges.sh
#
# SOURCES: one or more URLs of plain-text lists, one CIDR range per line.
# The script refuses a short download, does nothing when the list is unchanged,
# and restores the previous file if nginx -t fails.
set -euo pipefail

SOURCES="${SOURCES:?set SOURCES to the URLs of the published ranges}"
OUT="${OUT:-/etc/nginx/conf.d/realip-trusted.conf}"
MIN="${MIN:-2}"                        # refuse suspiciously short lists
NGINX_TEST="${NGINX_TEST:-nginx -t -q}"
RELOAD="${RELOAD:-systemctl reload nginx}"

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

{
  echo "# generated by update-ranges.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  for url in $SOURCES; do
    curl -fsS --max-time 20 "$url" |
      grep -E '^[0-9A-Fa-f:.]+/[0-9]{1,3}$' |
      sed 's/.*/set_real_ip_from &;/'
  done
} > "$tmp"

count=$(grep -c '^set_real_ip_from' "$tmp" || true)
if [ "$count" -lt "$MIN" ]; then
  echo "only $count ranges downloaded; keeping the current list" >&2
  exit 1
fi

if [ -f "$OUT" ] && cmp -s <(grep -v '^#' "$tmp") <(grep -v '^#' "$OUT"); then
  exit 0                               # unchanged, nothing to do
fi

[ -f "$OUT" ] && cp -p "$OUT" "$OUT.bak"
install -m 0644 "$tmp" "$OUT"
if $NGINX_TEST; then
  $RELOAD
else
  echo "nginx -t failed; restoring the previous list" >&2
  if [ -f "$OUT.bak" ]; then mv "$OUT.bak" "$OUT"; else rm -f "$OUT"; fi
  exit 1
fi
